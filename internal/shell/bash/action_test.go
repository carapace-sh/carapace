func TestActionRawValuesQuotingPartialCompletion(t *testing.T) {
	t.Setenv("CARAPACE_COMPLINE", "example 'w")
	t.Setenv("COMP_LINE", "example 'w")
	t.Setenv("COMP_POINT", strconv.Itoa(len("example 'w")))
	t.Setenv("COMP_TYPE", COMP_TYPE_NORMAL)
	args, err := Patch([]string{"bash"})
	if err != nil {
		t.Fatal(err)
	}

	// the collapsed common prefix is a partial value which readline completes to a full quoted word
	actual := ActionRawValues(args[len(args)-1], common.Meta{}, common.RawValuesFrom("words.txt", "work.txt"))
	if expected := "true\001'wor'"; actual != expected {
		t.Errorf("expected %q, got %q", expected, actual)
	}
}
